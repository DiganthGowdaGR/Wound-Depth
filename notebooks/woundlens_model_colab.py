# ------------------------------------------------------------
# 2. Extract raw visit features
# ------------------------------------------------------------

def extract_visit_features(scene_path):
    """
    Extract exactly the same RGB, thermal and depth features
    that were used during model training.
    """

    rgb_path = os.path.join(scene_path, "photo.png")
    thermal_path = os.path.join(scene_path, "thermal.png")
    depth_path = os.path.join(scene_path, "depth.png")

    rgb_bgr = cv2.imread(rgb_path)
    thermal_bgr = cv2.imread(thermal_path)
    depth_bgr = cv2.imread(depth_path)

    if rgb_bgr is None:
        raise FileNotFoundError(f"Missing RGB: {rgb_path}")

    if thermal_bgr is None:
        raise FileNotFoundError(f"Missing thermal: {thermal_path}")

    if depth_bgr is None:
        raise FileNotFoundError(f"Missing depth: {depth_path}")

    rgb = cv2.cvtColor(
        rgb_bgr,
        cv2.COLOR_BGR2RGB
    )

    thermal = cv2.cvtColor(
        thermal_bgr,
        cv2.COLOR_BGR2GRAY
    )

    depth = cv2.cvtColor(
        depth_bgr,
        cv2.COLOR_BGR2GRAY
    )

    r = rgb[:, :, 0]
    g = rgb[:, :, 1]
    b = rgb[:, :, 2]

    return {
        "rgb_r_mean": float(np.mean(r)),
        "rgb_g_mean": float(np.mean(g)),
        "rgb_b_mean": float(np.mean(b)),

        "rgb_r_std": float(np.std(r)),
        "rgb_g_std": float(np.std(g)),
        "rgb_b_std": float(np.std(b)),

        "thermal_mean": float(np.mean(thermal)),
        "thermal_std": float(np.std(thermal)),
        "thermal_p25": float(np.percentile(thermal, 25)),
        "thermal_p50": float(np.percentile(thermal, 50)),
        "thermal_p75": float(np.percentile(thermal, 75)),

        "depth_mean": float(np.mean(depth)),
        "depth_std": float(np.std(depth)),
        "depth_p25": float(np.percentile(depth, 25)),
        "depth_p50": float(np.percentile(depth, 50)),
        "depth_p75": float(np.percentile(depth, 75)),
    }


# ------------------------------------------------------------
# 3. Calculate previous -> current percentage changes
# ------------------------------------------------------------

def build_change_features(previous, current):
    """
    Convert two visit feature dictionaries into the exact
    percentage-change features expected by the trained model.
    """

    output = {}

    base_features = [
        "rgb_r_mean",
        "rgb_g_mean",
        "rgb_b_mean",
        "rgb_r_std",
        "rgb_g_std",
        "rgb_b_std",

        "thermal_mean",
        "thermal_std",
        "thermal_p25",
        "thermal_p50",
        "thermal_p75",

        "depth_mean",
        "depth_std",
        "depth_p25",
        "depth_p50",
        "depth_p75",
    ]

    for feature in base_features:

        prev_value = float(previous[feature])
        curr_value = float(current[feature])

        denominator = (
            abs(prev_value)
            if abs(prev_value) > 1e-6
            else 1e-6
        )

        pct_change = (
            (curr_value - prev_value)
            / denominator
        ) * 100.0

        output[
            f"{feature}_pct_change"
        ] = pct_change

    return output


# ------------------------------------------------------------
# 4. Final inference function
# ------------------------------------------------------------

def analyze_followup(previous_scene, current_scene):
    """
    Analyze longitudinal multimodal change between two visits.
    """

    previous = extract_visit_features(
        previous_scene
    )

    current = extract_visit_features(
        current_scene
    )

    change_features = build_change_features(
        previous,
        current
    )

    # Keep exact training feature order.
    X = pd.DataFrame(
        [[change_features[name] for name in model_features]],
        columns=model_features
    )

    X_scaled = scaler.transform(X)

    # Higher = more unusual multimodal change.
    score = float(
        -change_model.decision_function(
            X_scaled
        )[0]
    )

    low_threshold = float(
        thresholds["low_threshold"]
    )

    high_threshold = float(
        thresholds["high_threshold"]
    )

    if score < low_threshold:
        category = "LOW CHANGE"

    elif score < high_threshold:
        category = "MODERATE CHANGE"

    else:
        category = "HIGH CHANGE"


    # --------------------------------------------------------
    # Helpful modality-level summaries for the UI
    # --------------------------------------------------------

    rgb_keys = [
        key for key in change_features
        if key.startswith("rgb_")
    ]

    thermal_keys = [
        key for key in change_features
        if key.startswith("thermal_")
    ]

    depth_keys = [
        key for key in change_features
        if key.startswith("depth_")
    ]


    def mean_abs(keys):
        return float(
            np.mean([
                abs(change_features[key])
                for key in keys
            ])
        )


    result = {
        "change_score": score,
        "change_level": category,

        "rgb_change_index":
            mean_abs(rgb_keys),

        "thermal_change_index":
            mean_abs(thermal_keys),

        "depth_change_index":
            mean_abs(depth_keys),

        "review_required":
            category == "HIGH CHANGE"
    }

    return result


