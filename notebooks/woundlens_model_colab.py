# ============================================================
# WOUNDLENS MODEL — STEP 4
# Build longitudinal visit-to-visit change features.
#
# PURPOSE:
# Compare the SAME patient across visits.
#
# IMPORTANT:
# We are measuring multimodal CHANGE.
# We are NOT claiming that change = healing or infection.
# ============================================================

import numpy as np
import pandas as pd


# ------------------------------------------------------------
# 1. Select numerical multimodal features
# ------------------------------------------------------------

feature_columns = [
    # RGB
    "rgb_r_mean",
    "rgb_g_mean",
    "rgb_b_mean",
    "rgb_r_std",
    "rgb_g_std",
    "rgb_b_std",

    # Thermal rendered image
    "thermal_mean",
    "thermal_std",
    "thermal_p25",
    "thermal_p50",
    "thermal_p75",

    # Depth rendered image
    "depth_mean",
    "depth_std",
    "depth_p25",
    "depth_p50",
    "depth_p75",
]


# ------------------------------------------------------------
# 2. Sort by patient and acquisition day
# ------------------------------------------------------------

df_sorted = (
    features_df
    .sort_values(
        ["case", "day"]
    )
    .reset_index(drop=True)
)


# ------------------------------------------------------------
# 3. Build visit-to-visit pairs
#
# Example:
#
# case_17
# day_1  -> day_58
# day_58 -> day_72
# day_72 -> day_79
# ------------------------------------------------------------

change_records = []

for case_name, group in df_sorted.groupby("case"):

    group = (
        group
        .sort_values("day")
        .reset_index(drop=True)
    )

    # Need at least two visits.
    if len(group) < 2:
        continue

    for i in range(1, len(group)):

        previous = group.iloc[i - 1]
        current = group.iloc[i]

        record = {
            "case": case_name,
            "previous_day": int(previous["day"]),
            "current_day": int(current["day"]),
            "days_between":
                int(current["day"] - previous["day"]),
        }


        # ----------------------------------------------------
        # Calculate absolute and percentage change
        # ----------------------------------------------------

        for feature in feature_columns:

            prev_value = float(previous[feature])
            curr_value = float(current[feature])

            absolute_change = (
                curr_value - prev_value
            )

            # Prevent division-by-zero problems.
            denominator = (
                abs(prev_value)
                if abs(prev_value) > 1e-6
                else 1e-6
            )

            percentage_change = (
                absolute_change
                / denominator
            ) * 100.0


            record[
                f"{feature}_delta"
            ] = absolute_change

            record[
                f"{feature}_pct_change"
            ] = percentage_change


        change_records.append(record)


# ------------------------------------------------------------
# 4. Create longitudinal DataFrame
# ------------------------------------------------------------

changes_df = pd.DataFrame(
    change_records
)

print("=" * 70)
print("LONGITUDINAL CHANGE DATASET")
print("=" * 70)

print(
    "Visit-to-visit comparisons:",
    len(changes_df)
)

print(
    "Cases represented:",
    changes_df["case"].nunique()
)

display(
    changes_df[
        [
            "case",
            "previous_day",
            "current_day",
            "days_between"
        ]
    ].head(20)
)


# ------------------------------------------------------------
# 5. Build feature matrix for change scoring
#
# We use percentage changes because different modalities
# have different raw numerical ranges.
# ------------------------------------------------------------

change_feature_columns = [
    f"{feature}_pct_change"
    for feature in feature_columns
]

X = (
    changes_df[
        change_feature_columns
    ]
    .replace(
        [np.inf, -np.inf],
        np.nan
    )
    .fillna(0)
)


# ------------------------------------------------------------
# 6. Robust normalization
#
# StandardScaler makes the different feature ranges comparable.
# ------------------------------------------------------------

from sklearn.preprocessing import StandardScaler

scaler = StandardScaler()

X_scaled = scaler.fit_transform(X)


# ------------------------------------------------------------
# 7. Calculate multimodal change magnitude
#
# Euclidean distance from "no change".
#
# Larger score =
# larger overall difference between visits.
#
# NOTE:
# Large change does NOT automatically mean worsening.
# ------------------------------------------------------------

raw_change_score = np.sqrt(
    np.mean(
        np.square(X_scaled),
        axis=1
    )
)

changes_df[
    "multimodal_change_score"
] = raw_change_score


# ------------------------------------------------------------
# 8. Convert score into simple prototype categories
#
# These are DATA-RELATIVE categories,
# NOT clinical severity categories.
# ------------------------------------------------------------

low_threshold = np.percentile(
    raw_change_score,
    33
)

high_threshold = np.percentile(
    raw_change_score,
    67
)


def categorize_change(score):

    if score < low_threshold:
        return "LOW CHANGE"

    elif score < high_threshold:
        return "MODERATE CHANGE"

    else:
        return "HIGH CHANGE"


changes_df[
    "change_category"
] = changes_df[
    "multimodal_change_score"
].apply(
    categorize_change
)


# ------------------------------------------------------------
# 9. Rank most changed visit pairs
# ------------------------------------------------------------

ranked_changes = (
    changes_df
    .sort_values(
        "multimodal_change_score",
        ascending=False
    )
)


print("\n" + "=" * 70)
print("TOP MULTIMODAL CHANGES")
print("=" * 70)

