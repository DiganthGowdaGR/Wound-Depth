#
# This learns what typical multimodal change looks like
# across our longitudinal dataset.
# ------------------------------------------------------------

change_model = IsolationForest(
    n_estimators=200,
    contamination="auto",
    random_state=42
)

change_model.fit(X_scaled)


# ------------------------------------------------------------
# 5. Generate model anomaly/change scores
#
# sklearn:
# lower decision_function = more unusual
#
# We reverse it so:
# higher score = more unusual multimodal change.
# ------------------------------------------------------------

model_df["model_change_score"] = (
    -change_model.decision_function(X_scaled)
)


# ------------------------------------------------------------
# 6. Convert score to prototype categories
#
# DATA-RELATIVE categories only.
# ------------------------------------------------------------

scores = model_df["model_change_score"]

low_threshold = np.percentile(scores, 33)
high_threshold = np.percentile(scores, 67)


def model_category(score):

    if score < low_threshold:
        return "LOW CHANGE"

    elif score < high_threshold:
        return "MODERATE CHANGE"

    else:
        return "HIGH CHANGE"


model_df["model_change_category"] = (
    model_df["model_change_score"]
    .apply(model_category)
)


