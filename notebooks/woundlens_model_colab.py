# ------------------------------------------------------------
# 7. Connected components
#
# Keep meaningful components inside the wound region.
# Do NOT blindly keep the largest region if it becomes the leg.
# ------------------------------------------------------------

num_labels, labels, stats, centroids = (
    cv2.connectedComponentsWithStats(
        binary,
        connectivity=8
    )
)

clean_mask = np.zeros_like(binary)

# We expect the wound around the left-middle/lower area.
target_center = np.array([
    95,   # expected x center
    135   # expected y center
])


best_score = None
best_label = None

for label_id in range(1, num_labels):

    area = stats[
        label_id,
        cv2.CC_STAT_AREA
    ]

    if area < 150:
        continue

    cx, cy = centroids[label_id]

    center = np.array([cx, cy])

    distance = np.linalg.norm(
        center - target_center
    )

    # Prefer:
    # - reasonably large regions
    # - regions close to the expected wound location
    score = area / (1 + distance)

    if best_score is None or score > best_score:
        best_score = score
        best_label = label_id


if best_label is not None:
    clean_mask[
        labels == best_label
    ] = 255
else:
    print("WARNING: No suitable wound component detected.")
    clean_mask = binary.copy()


