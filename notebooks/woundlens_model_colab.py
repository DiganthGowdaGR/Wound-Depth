# ------------------------------------------------------------
# 1. Helper functions
# ------------------------------------------------------------

def extract_case_number(case_name):
    """case_17 -> 17"""
    try:
        return int(case_name.split("_")[1])
    except Exception:
        return None


def extract_day_number(day_name):
    """day_156 -> 156"""
    try:
        return int(day_name.split("_")[1])
    except Exception:
        return None


def load_rgb(path):
    """Load normal RGB image."""
    image = cv2.imread(path, cv2.IMREAD_COLOR)

    if image is None:
        return None

    return cv2.cvtColor(
        image,
        cv2.COLOR_BGR2RGB
    )


def load_grayscale(path):
    """
    Load an image and convert it to grayscale.

    NOTE:
    thermal.png and depth.png in this processed dataset
    are rendered 8-bit images.

    Their pixel values are NOT treated as:
    - actual temperature in °C
    - physical wound depth
    """

    image = cv2.imread(
        path,
        cv2.IMREAD_COLOR
    )

    if image is None:
        return None

    return cv2.cvtColor(
        image,
        cv2.COLOR_BGR2GRAY
    )


def image_statistics(image):
    """Basic intensity statistics."""

    return {
        "mean": float(np.mean(image)),
        "std": float(np.std(image)),
        "min": float(np.min(image)),
        "max": float(np.max(image)),
        "p25": float(np.percentile(image, 25)),
        "p50": float(np.percentile(image, 50)),
        "p75": float(np.percentile(image, 75)),
    }


# ------------------------------------------------------------
# 2. Build scene-level feature records
# ------------------------------------------------------------

records = []

