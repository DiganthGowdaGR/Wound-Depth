    case_name = case["case"]
    case_path = case["path"]

    for day_name in case["days"]:

        day_number = extract_day_number(day_name)

        day_path = os.path.join(
            case_path,
            day_name
        )

        # Find all scene folders recursively.
        for root, dirs, files in os.walk(day_path):

            if not os.path.basename(root).startswith("scene_"):
                continue

            file_set = set(files)

            # We only use scenes having all 3 modalities.
